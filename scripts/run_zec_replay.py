    if eid in seen_ids:
        dup_count += 1
        print(f"  DUPLICATE: {eid}")
    seen_ids.add(eid)
    # Both fields: signed_amount (event amount, sign convention) and
    # the funding cost impact.  Verify numeric field matches the journal.
    journal_amt = next((ev["signed_amount"] for ev in events
                        if ev["event_id"] == eid), None)
    ev_amt = fe.get("funding_amount")
