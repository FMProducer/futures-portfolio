# --- 6. Funding event verification (dual-field: signed_amount + funding_paid) ---
funding_evs = [e for e in ev1 if e.get("kind") == "funding"]
print(f"\n=== FUNDING EVENTS: {len(funding_evs)} ===")
seen_ids = set()
dup_count = 0
