# --- 2. Generate funding scenario ---
# Typical ZECUSDT funding at 00:00, 08:00, 16:00 UTC.
# Generate events for Oct 10 00:00 through Oct 19 16:00 UTC (30 events).
# Include: regular debits, credits, a micro-payment, and a large debit.
import math

events = []
eid = 0
for day_offset in range(10):  # Oct 10 through Oct 19
    for hour in (0, 8, 16):
        ts = 1791590400 + day_offset * 86400 + hour * 3600  # Oct 10 00:00 UTC base
        if ts > 1792454400:  # past Oct 19 23:59
            continue

        # realistic ZECUSDT funding rates (annualised ~9% -> ~0.01% per 8h)
        # vary sign and magnitude
        day_in_window = day_offset
        if day_in_window <= 2:
            rate = -0.000025 * (1.0 + 0.5 * day_in_window)  # negative, growing
        elif day_in_window <= 5:
            rate = 0.000015  # positive credits
        elif day_in_window <= 7:
            rate = -0.000080 * (1.0 + (day_in_window - 5))  # larger negative
        else:
            rate = -0.000010  # light negative

        # Notional: 35% of 1000 USDT * 7x lev ~= 2450 USDT at ZEC ~200
        # Funding per 8h = notional x rate
        notional = 2450.0
        signed_amount = notional * rate

        # Add a micro-payment on day 6, 08:00
        if day_offset == 6 and hour == 8:
            signed_amount = -0.000049  # micro

        # Add a large debit on day 8, 00:00 to test shortfall
        if day_offset == 8 and hour == 0:
            signed_amount = -4500.0  # guaranteed shortfall regardless of V growth

        events.append({
            "event_id": f"zec_fund:{eid:04d}",
            "signed_amount": round(signed_amount, 10),
            "event_time": float(ts),
            "source": "scenario",
            "source_ref": f"zec_replay_{day_offset}_{hour}",
            "portfolio_id": "default",
            "symbol": "ZECUSDT",
            "asset": "USDT",
            "raw_payload_hash": "",
            "status": "received",
            "applied_at": None,
            "kind": "FUNDING_FEE",
        })
        eid += 1

scenario_path = os.path.join(ROOT, "data", "zec_funding_scenario_replay.json")
with open(scenario_path, "w", encoding="utf-8") as f:
    json.dump(events, f, indent=2)
print(f"\nFunding scenario: {len(events)} events -> {scenario_path}")
