    ("journal<->event mismatches == 0", mismatch_count == 0),
    ("post-shortfall invariants", post_ok),
    ("attribution residual < 0.01", residual_ok),
    ("equity[-1] == final_tpv", equity_tail_ok),
    ("accounting_ok (engine)", accounting_ok),
    ("attribution funding == engine funding_paid", funding_parity_ok),
